-- Fudepan Phase 2: note upload.
--
-- Upload flow (all writes happen in server code with the service role):
--   1. reserve_note_upload      a short-lived reservation for one storage path
--   2. (browser uploads the image straight to Storage with a signed upload token)
--   3. complete_note_upload     note row + `note.uploaded` audit event, in one transaction
--   on failure:
--      claim_note_upload_failure   pending -> failing, so nothing can complete it any more
--      (server removes the stored object)
--      record_note_upload_failure  failing -> failed + `note.upload_failed` audit event
--   rejections before a reservation exists:
--      record_note_upload_rejection  `note.upload_failed` audit event (members only)
--   abandoned uploads (browser closed mid-upload):
--      expire_note_upload          expired reservations -> `note.upload_abandoned`
--
-- Browser roles (anon, authenticated) get no Storage policies for the `notes`
-- bucket and no access to note_uploads or these functions. Audit payloads hold
-- IDs, codes, sizes, and content types only: never file names, paths, or URLs.

-- ---------------------------------------------------------------------------
-- Storage bucket: private, 10 MB, JPEG / PNG / WebP only
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('notes', 'notes', false, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- ---------------------------------------------------------------------------
-- Upload reservations
-- ---------------------------------------------------------------------------
create table public.note_uploads (
  note_id uuid primary key,
  household_id uuid not null references public.households (id),
  uploaded_by uuid not null references auth.users (id),
  object_path text not null unique,
  content_type text not null,
  size_bytes integer not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  -- Longer than the 2-hour signed upload token, so an expired reservation can
  -- never receive another upload after it has been cleaned up.
  expires_at timestamptz not null default now() + interval '3 hours',
  completed_at timestamptz,
  constraint note_uploads_content_type_valid check (
    content_type in ('image/jpeg', 'image/png', 'image/webp')
  ),
  constraint note_uploads_size_valid check (size_bytes > 0 and size_bytes <= 10485760),
  constraint note_uploads_status_valid check (
    status in ('pending', 'failing', 'failed', 'completed', 'expired')
  ),
  -- {household_id}/{note_id}/{epoch_ms}-note.{jpg|png|webp}, generated by the server.
  constraint note_uploads_object_path_format check (
    object_path ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}/[0-9]{13}-note\.(jpg|png|webp)$'
    and starts_with(object_path, household_id::text || '/' || note_id::text || '/')
  ),
  constraint note_uploads_extension_matches_type check (
    (content_type = 'image/jpeg' and object_path like '%.jpg')
    or (content_type = 'image/png' and object_path like '%.png')
    or (content_type = 'image/webp' and object_path like '%.webp')
  )
);

create index note_uploads_household_status_idx on public.note_uploads (household_id, status, expires_at);
create index note_uploads_uploaded_by_idx on public.note_uploads (uploaded_by, status, expires_at);

comment on table public.note_uploads is
  'Server-only reservations for direct-to-Storage note uploads. Not visible to browser roles.';

alter table public.note_uploads enable row level security;
revoke all on table public.note_uploads from anon, authenticated;
grant all on table public.note_uploads to service_role;

-- Every note image lives under its own household and note prefix.
alter table public.notes
  add constraint notes_image_path_in_household check (
    starts_with(image_path, household_id::text || '/' || id::text || '/')
  );

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------
create function private.assert_audit_code(p_value text, p_name text)
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p_value is null or p_value !~ '^[a-z][a-z_]{0,39}$' then
    raise exception 'invalid_%', p_name using errcode = '22023';
  end if;
end;
$$;

create function private.can_upload_notes(p_household_id uuid, p_user_id uuid)
returns boolean
language sql
stable
set search_path = ''
as $$
  select exists (
    select 1
    from public.household_members m
    where m.household_id = p_household_id
      and m.user_id = p_user_id
      and m.is_active
      and m.role <> 'care_recipient'
  );
$$;

revoke all on function private.assert_audit_code(text, text) from public;
revoke all on function private.can_upload_notes(uuid, uuid) from public;
grant usage on schema private to service_role;
grant execute on function private.assert_audit_code(text, text) to service_role;
grant execute on function private.can_upload_notes(uuid, uuid) to service_role;

-- ---------------------------------------------------------------------------
-- 1. Reserve
-- ---------------------------------------------------------------------------
create function public.reserve_note_upload(
  p_note_id uuid,
  p_household_id uuid,
  p_user_id uuid,
  p_object_path text,
  p_content_type text,
  p_size_bytes integer
)
returns timestamptz
language plpgsql
set search_path = ''
as $$
declare
  v_pending integer;
  v_expires_at timestamptz;
begin
  if not private.can_upload_notes(p_household_id, p_user_id) then
    raise exception 'not_allowed' using errcode = 'P0001';
  end if;

  -- Limit unfinished uploads per person, so abandoned uploads cannot pile up.
  select count(*) into v_pending
  from public.note_uploads u
  where u.uploaded_by = p_user_id
    and u.status = 'pending'
    and u.expires_at > now();

  if v_pending >= 5 then
    raise exception 'too_many_pending' using errcode = 'P0001';
  end if;

  insert into public.note_uploads (note_id, household_id, uploaded_by, object_path, content_type, size_bytes)
  values (p_note_id, p_household_id, p_user_id, p_object_path, p_content_type, p_size_bytes)
  returning expires_at into v_expires_at;

  return v_expires_at;
end;
$$;

-- ---------------------------------------------------------------------------
-- 2. Complete: note row and audit event commit together or not at all
-- ---------------------------------------------------------------------------
create function public.complete_note_upload(
  p_note_id uuid,
  p_user_id uuid,
  p_size_bytes integer,
  p_content_type text
)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  r public.note_uploads;
  v_audit_id uuid;
begin
  select * into r
  from public.note_uploads u
  where u.note_id = p_note_id
  for update;

  if not found or r.uploaded_by <> p_user_id then
    raise exception 'upload_not_found' using errcode = 'P0001';
  end if;
  if r.status <> 'pending' then
    raise exception 'upload_not_pending' using errcode = 'P0001';
  end if;
  if r.expires_at <= now() then
    raise exception 'upload_expired' using errcode = 'P0001';
  end if;
  if p_content_type is distinct from r.content_type
    or p_size_bytes is null or p_size_bytes <= 0 or p_size_bytes > 10485760 then
    raise exception 'upload_invalid' using errcode = 'P0001';
  end if;
  -- Membership can change between reserving and completing.
  if not private.can_upload_notes(r.household_id, p_user_id) then
    raise exception 'not_allowed' using errcode = 'P0001';
  end if;

  insert into public.notes (id, household_id, uploaded_by, image_path, status)
  values (r.note_id, r.household_id, r.uploaded_by, r.object_path, 'uploaded');

  insert into public.audit_events (household_id, actor_type, actor_id, event_type, payload)
  values (
    r.household_id,
    'human',
    p_user_id,
    'note.uploaded',
    jsonb_build_object(
      'note_id', r.note_id,
      'content_type', r.content_type,
      'size_bytes', p_size_bytes,
      'status', 'uploaded'
    )
  )
  returning id into v_audit_id;

  update public.note_uploads
  set status = 'completed', completed_at = now(), size_bytes = p_size_bytes
  where note_id = p_note_id;

  return v_audit_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 3. Failure: claim first (so nothing can complete it), clean up, then record
-- ---------------------------------------------------------------------------
create function public.claim_note_upload_failure(p_note_id uuid, p_user_id uuid)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.note_uploads
  set status = 'failing'
  where note_id = p_note_id
    and uploaded_by = p_user_id
    and status = 'pending';
  return found;
end;
$$;

create function public.record_note_upload_failure(
  p_note_id uuid,
  p_user_id uuid,
  p_stage text,
  p_reason text,
  p_object_removed boolean
)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  r public.note_uploads;
  v_audit_id uuid;
begin
  perform private.assert_audit_code(p_stage, 'stage');
  perform private.assert_audit_code(p_reason, 'reason');

  update public.note_uploads u
  set status = 'failed'
  where u.note_id = p_note_id
    and u.uploaded_by = p_user_id
    and u.status = 'failing'
  returning * into r;

  if not found then
    raise exception 'upload_not_failing' using errcode = 'P0001';
  end if;

  insert into public.audit_events (household_id, actor_type, actor_id, event_type, payload)
  values (
    r.household_id,
    'human',
    p_user_id,
    'note.upload_failed',
    jsonb_build_object(
      'note_id', r.note_id,
      'stage', p_stage,
      'reason', p_reason,
      'object_removed', coalesce(p_object_removed, false)
    )
  )
  returning id into v_audit_id;

  return v_audit_id;
end;
$$;

-- Rejections before a reservation exists (for example a file that is too large).
-- Only written for members, so nobody can write into another household's trail.
create function public.record_note_upload_rejection(
  p_household_id uuid,
  p_user_id uuid,
  p_stage text,
  p_reason text
)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_audit_id uuid;
begin
  perform private.assert_audit_code(p_stage, 'stage');
  perform private.assert_audit_code(p_reason, 'reason');

  if not exists (
    select 1
    from public.household_members m
    where m.household_id = p_household_id
      and m.user_id = p_user_id
      and m.is_active
  ) then
    raise exception 'not_member' using errcode = 'P0001';
  end if;

  insert into public.audit_events (household_id, actor_type, actor_id, event_type, payload)
  values (
    p_household_id,
    'human',
    p_user_id,
    'note.upload_failed',
    jsonb_build_object('stage', p_stage, 'reason', p_reason)
  )
  returning id into v_audit_id;

  return v_audit_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. Abandoned uploads
-- ---------------------------------------------------------------------------
-- Called after the server has removed the stored object (if any) for an
-- expired reservation. Returns true when the reservation changed state.
create function public.expire_note_upload(p_note_id uuid, p_object_removed boolean)
returns boolean
language plpgsql
set search_path = ''
as $$
declare
  r public.note_uploads;
  v_previous text;
begin
  select * into r
  from public.note_uploads u
  where u.note_id = p_note_id
  for update;

  if not found
    or r.status not in ('pending', 'failing', 'failed')
    or r.expires_at > now() then
    return false;
  end if;

  v_previous := r.status;

  update public.note_uploads set status = 'expired' where note_id = p_note_id;

  -- Failed uploads were already audited; only record new information.
  if v_previous <> 'failed' or coalesce(p_object_removed, false) then
    insert into public.audit_events (household_id, actor_type, event_type, payload)
    values (
      r.household_id,
      'system',
      'note.upload_abandoned',
      jsonb_build_object(
        'note_id', r.note_id,
        'previous_status', v_previous,
        'object_removed', coalesce(p_object_removed, false)
      )
    );
  end if;

  return true;
end;
$$;

